import esbuild from "esbuild";
import process from "process";
import path from "path";
import fs from "fs";

// 1. Define your target vault plugin path here
const targetDir = "/Users/peonat/Library/Mobile Documents/iCloud~md~obsidian/Documents/Peonat/.obsidian/plugins/nexus-graph";

// 2. Helper function to copy necessary non-JS files
function copyPluginFiles() {
    if (!fs.existsSync(targetDir)) {
        fs.mkdirSync(targetDir, { recursive: true });
    }

    // Copy manifest.json
    if (fs.existsSync("manifest.json")) {
        fs.copyFileSync("manifest.json", path.join(targetDir, "manifest.json"));
    }

    // Copy styles.css if it exists in your project
    if (fs.existsSync("styles.css")) {
        fs.copyFileSync("styles.css", path.join(targetDir, "styles.css"));
    }

    console.log(`✨ Copied manifest.json and styles.css to vault: ${targetDir}`);
}

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/tree",
    "codemirror"
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: path.join(targetDir, "main.js"), // Compiles main.js directly to your vault
  banner: {
    js: banner,
  },
});

if (prod) {
  await context.rebuild();
  copyPluginFiles();
  process.exit(0);
} else {
  await context.watch();
  // Copy files initially on startup, and esbuild will handle main.js updates on watch
  copyPluginFiles();
}